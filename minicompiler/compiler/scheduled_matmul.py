"""Replace eligible Relax matmuls with a checked, scheduled CPU call_tir.

This is an explicit opt-in graph rewrite before the standard Relax pipeline.
The TIR is generated by this project; LLVM lowering and the VM are TVM's.
"""
import tvm
from tvm import relax
from tvm.relax.dpl import is_op, rewrite_call, wildcard

from minicompiler.schedules.matmul_cpu import STAGES, make_matmul


def _shape(expr):
    ty = getattr(expr, "ty", None)
    if not isinstance(ty, relax.TensorType) or str(ty.dtype) != "float32" or not isinstance(ty.shape, relax.ShapeExpr):
        return None
    if any(not isinstance(d, tvm.tirx.IntImm) or int(d.value) <= 0 for d in ty.shape):
        return None
    return tuple(int(d.value) for d in ty.shape)


def _eligible(call):
    if not isinstance(call, relax.Call) or not isinstance(call.op, tvm.ir.Op) or call.op.name != "relax.matmul" or len(call.args) != 2:
        return None
    a, b, out = _shape(call.args[0]), _shape(call.args[1]), _shape(call)
    if a is None or b is None or out is None or len(a) != 2 or len(b) != 2:
        return None
    m, k = a
    k2, n = b
    if k != k2 or out != (m, n) or str(call.attrs.out_dtype) not in ("", "void", "float32", "None"):
        return None
    return m, k, n


def _primitive(func):
    return func.attrs is not None and "Primitive" in func.attrs and int(func.attrs["Primitive"]) != 0


def run_scheduled_matmul(mod, *, stage="vectorize"):
    """Return (new module, report), or the original module on an error.

    Only positive static rank-2 float32 matmuls are changed. Dynamic, batched,
    non-FP32, and other operators remain untouched. Primitive functions are
    excluded. It is not a drop-in rewrite after linear fusion.
    """
    if stage not in STAGES:
        raise ValueError(f"unknown schedule stage: {stage}")
    report = {"status": "ok", "stage": stage, "rewrites": 0, "shapes": [], "error": None}
    try:
        shapes = set()
        @relax.expr_functor.visitor
        class Visitor(relax.PyExprVisitor):
            def visit_call_(self, call):
                shape = _eligible(call)
                if shape is not None:
                    shapes.add(shape)
                super().visit_call_(call)
        for _, func in mod.functions.items():
            if isinstance(func, relax.Function) and not _primitive(func):
                Visitor().visit_expr(func)
        builder = relax.BlockBuilder(mod)
        kernels = {}
        for shape in sorted(shapes):
            prim = make_matmul(*shape, stage)["main"].without_attr("global_symbol")
            kernels[shape] = builder.add_func(prim, "scheduled_matmul")
        out = builder.get()
        left, right = wildcard(), wildcard()
        pattern = is_op("relax.matmul")(left, right)
        def rewrite(call, matched):
            shape = _eligible(call)
            if shape is None:
                return call
            report["rewrites"] += 1
            report["shapes"].append(list(shape))
            return relax.op.call_tir(kernels[shape], (call.args[0], call.args[1]), out_ty=call.ty)
        for gv, func in list(out.functions.items()):
            if isinstance(func, relax.Function) and not _primitive(func):
                out.update_func(gv, rewrite_call(pattern, rewrite, func))
        relax.analysis.well_formed(out)
        return out, report
    except Exception as exc:
        report.update(status="failed", error=f"{type(exc).__name__}: {exc}", rewrites=0, shapes=[])
        return mod, report
